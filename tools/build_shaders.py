"""Compile the runtime's own GLSL shaders (runtime/shaders/*.comp, *.vert, *.frag) into C headers of SPIR-V words.

Each runtime/shaders/<name>.comp (or .vert, .frag: one name per shader) becomes runtime/<name>_spv.h, which declares `static const uint32_t <name>_spv[]`
and records the SHA-256 of the source it came from. The headers are committed, so building totk.exe needs no shader
compiler; tools/build_game.py refuses to build when a header no longer matches its source. Run this after editing a
shader. Needs glslc and spirv-val from MSYS2 UCRT64 (package mingw-w64-ucrt-x86_64-shaderc, spirv-tools).

    python tools/build_shaders.py [--check] [--variants-only]
"""

import argparse
import hashlib
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BIN = Path(r'C:\msys64\ucrt64\bin')   # Windows; elsewhere glslc and spirv-val come from PATH
WIN = os.name == 'nt'
TARGET = 'vulkan1.1'
STAGES = {'.comp': 'compute', '.vert': 'vertex', '.frag': 'fragment'}
# Shaders that also get a header for another SPIR-V target, <name><suffix>_spv.h with the array <name><suffix>_spv: the
# one a Vulkan 1.2 device loads where the default header's SPIR-V is too new for it. name: (suffix, target env).
VARIANTS = {'dlaa_mv': ('_12', 'vulkan1.2')}   # vk_dlaa.c; the default header is SPIR-V 1.6, Vulkan 1.2 takes up to 1.5


def source_hash(src):
    return hashlib.sha256(src.read_bytes().replace(b'\r\n', b'\n')).hexdigest()   # the same on a CRLF checkout


def header_of(src, words, suffix=''):
    name = src.stem + suffix
    lines = [f'// Generated by tools/build_shaders.py from runtime/shaders/{src.name}; do not edit.',
             f'// source sha256 {source_hash(src)}',
             '#pragma once',
             '#include <stdint.h>',
             f'static const uint32_t {name}_spv[] = {{']
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def header_path(src, suffix=''):
    return src.parent.parent / f'{src.stem}{suffix}_spv.h'


def sources(runtime):
    return sorted(p for p in (runtime / 'shaders').iterdir() if p.suffix in STAGES)


def stale(runtime):
    """Shader sources under runtime/shaders whose header is missing or records another source hash."""
    out = []
    for src in sources(runtime):
        for suffix in ('',) + ((VARIANTS[src.stem][0],) if src.stem in VARIANTS else ()):
            h = header_path(src, suffix)
            if not h.exists() or f'// source sha256 {source_hash(src)}' not in h.read_text(encoding='utf-8'):
                out.append(h)
    return out


def compile_one(src, suffix='', target=TARGET):
    with tempfile.TemporaryDirectory() as tmp:
        spv = Path(tmp) / 'out.spv'
        subprocess.run([str(BIN / 'glslc.exe') if WIN else 'glslc', '-O', f'--target-env={target}', f'-fshader-stage={STAGES[src.suffix]}',
                        '-o', str(spv), str(src)], check=True)
        subprocess.run([str(BIN / 'spirv-val.exe') if WIN else 'spirv-val', f'--target-env', target, str(spv)], check=True)
        data = spv.read_bytes()
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    header_path(src, suffix).write_text(header_of(src, words, suffix), encoding='utf-8', newline='\n')
    print(f'{header_path(src, suffix).relative_to(ROOT)}: {len(words)} words')


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='only report headers that do not match their source')
    ap.add_argument('--variants-only', action='store_true',
                    help='write the VARIANTS headers only and leave the default ones as they are')
    ap.add_argument('--runtime', type=Path, default=ROOT / 'runtime')
    args = ap.parse_args()
    if args.check:
        bad = stale(args.runtime)
        for h in bad:
            print(f'{h}: stale, run tools/build_shaders.py')
        return 1 if bad else 0
    for src in sources(args.runtime):
        if not args.variants_only:
            compile_one(src)
        if src.stem in VARIANTS:
            compile_one(src, *VARIANTS[src.stem])
    return 0


if __name__ == '__main__':
    sys.exit(main())
